using System.Collections.Generic;
using System.Text;
using EntityLengths.Generator.Models;
using EntityLengths.Generator.Options;

namespace EntityLengths.Generator.Emit;

/// <summary>
/// Renders the constants class. Used for both the in-compilation output and the file written to
/// another project, so the two can never drift apart.
/// </summary>
internal static class ConstantsSourceBuilder
{
    public static string Build(
        string @namespace,
        IReadOnlyList<EntityConstants> entities,
        EntityLengthsGeneratorOptions options
    )
    {
        var sourceBuilder = new StringBuilder();
        sourceBuilder.AppendLine("// <auto-generated/>");
        sourceBuilder.AppendLine($"namespace {@namespace};");
        sourceBuilder.AppendLine();

        if (options.GenerateDocumentation)
        {
            sourceBuilder.AppendLine("/// <summary>");
            sourceBuilder.AppendLine(
                "/// Contains generated string length constants for entity properties"
            );
            sourceBuilder.AppendLine("/// </summary>");
        }

        sourceBuilder.AppendLine(
            $"public static partial class {options.GeneratedClassName} \r\n{{"
        );

        var isFirst = true;
        foreach (var entity in entities)
        {
            if (!isFirst)
                sourceBuilder.AppendLine();

            if (options.GenerateDocumentation)
            {
                sourceBuilder.AppendLine("\t/// <summary>");
                sourceBuilder.AppendLine($"\t/// Length constants for {entity.Name}");
                sourceBuilder.AppendLine("\t/// </summary>");
            }

            AppendEntityClass(sourceBuilder, entity, options);
            isFirst = false;
        }

        sourceBuilder.AppendLine("}");

        return sourceBuilder.ToString();
    }

    private static void AppendEntityClass(
        StringBuilder sourceBuilder,
        EntityConstants entity,
        EntityLengthsGeneratorOptions options
    )
    {
        sourceBuilder.AppendLine($"\tpublic static partial class {entity.Name}");
        sourceBuilder.AppendLine("\t{");

        foreach (var property in entity.Properties)
        {
            if (options.GenerateDocumentation)
            {
                sourceBuilder.AppendLine("\t\t/// <summary>");
                sourceBuilder.AppendLine($"\t\t/// Maximum length for {property.PropertyName}");
                sourceBuilder.AppendLine("\t\t/// </summary>");
            }

            sourceBuilder.AppendLine(
                $"\t\tpublic const int {property.PropertyName}{options.LengthSuffix} = {property.MaxLength};"
            );
        }

        sourceBuilder.AppendLine("\t}");
    }
}

/// <summary>
/// The resolved, deduplicated constants of a single generated nested class.
/// </summary>
internal sealed record EntityConstants(string Name, IReadOnlyList<PropertyMaxLength> Properties);
